/* ---------- Hero animation ----------
 * WavingPerson is a full-viewport scene by default
 * (`.waving-scene { min-height: 100vh }`). In the hero we want it to
 * occupy only its column and to have no background of its own. We:
 *   - wrap it in a 4:5 frame with a border + shadow so it reads as a
 *     hero image,
 *   - pass `transparent` to WavingPerson so it drops its gradient and
 *     decorative blurs,
 *   - leave the frame's background as `--nb-surface` (inherited) so
 *     the character sits directly on the hero surface,
 *   - use a scoped <style> block to override the scene's min-height
 *     and recenter the character inside the narrower box.
 */
const HeroAnimation = () => {
  return (
    <div
      className="hero-animation-root"
      style={{
        position: 'relative',
        width: '100%',
        maxWidth: '520px',
        margin: '0 auto',
        aspectRatio: '4 / 5',
        overflow: 'hidden',
        // No background here: the hero surface shows through, and
        // WavingPerson is transparent too. If you want a colored
        // stage behind the character, set e.g. '#1a1a2e'.
        background: 'transparent',
      }}
    >
      <div style={{ position: 'absolute', inset: 0 }}>
        <WavingPerson transparent />
      </div>

      <style>{`
        .hero-animation-root .waving-scene {
          min-height: 100%;
          height: 100%;
        }
        /* The scene offsets the character to the right on the splash
           screen; in the narrower hero box, recenter it. */
        .hero-animation-root .character-container {
          margin-left: 0;
        }
        /* Shrink the greeting so it fits inside the frame. */
        .hero-animation-root .greeting-text {
          font-size: clamp(2rem, 6vw, 3.5rem);
        }
        /* The greeting word is a white-to-blue gradient on the
           splash's dark background. On the light hero surface that
           reads washed out, so switch it to solid black. */
        .hero-animation-root .greeting-word {
          background: none;
          -webkit-text-fill-color: var(--nb-black);
          color: var(--nb-black);
        }
        .hero-animation-root .greeting-exclaim {
          color: var(--nb-pink);
        }
      `}</style>
    </div>
  );
};